#!/usr/bin/env bash
set -euo pipefail

usage() {
  echo "usage: $0 <widget-shards>" >&2
  exit 2
}

[ $# -eq 1 ] || usage
widget_shards=$1

root=$(cd "$(dirname "$0")/.." && pwd)
out=$root/test/shards
rm -rf "$out"
mkdir -p "$out"

unit=()
widget=()
for path in "$root"/test/*_test.dart; do
  if grep -qE 'testWidgets|WidgetTester' "$path"; then
    widget+=("$path")
  else
    unit+=("$path")
  fi
done

assign() {
  local shards=$1
  shift
  wc -l "$@" | grep -v ' total$' | sort -rn | awk -v n="$shards" '
    {
      best = 0
      for (i = 1; i < n; i++) if (load[i] < load[best]) best = i
      load[best] += $1
      print best, $2
    }'
}

write() {
  local shard=$1
  local file=$out/$shard.dart
  shift
  {
    echo "// Generated by tool/test-shards.sh."
    echo
    echo "import 'package:flutter_test/flutter_test.dart';"
    echo
    for path in "$@"; do
      local name
      name=$(basename "$path" .dart)
      echo "import '../$name.dart' as $name;"
    done
    echo
    echo "void main() {"
    for path in "$@"; do
      local name
      name=$(basename "$path" .dart)
      echo "  group('$name', $name.main);"
    done
    echo "}"
  } >"$file"
}

write unit "${unit[@]}"

declare -A batches
while read -r shard path; do
  batches[$shard]+="$path "
done < <(assign "$widget_shards" "${widget[@]}")

for shard in "${!batches[@]}"; do
  # shellcheck disable=SC2086
  write "widget_$(printf '%02d' "$shard")" ${batches[$shard]}
done
